import * as XLSX from "xlsx";
import { Transaction } from "./types";


export interface ExcelExportOptions {
  fileName?: string;
  sheetName?: string;
}


/**
 * Generate professional Excel file
 */
export function generateExcel(
  transactions: Transaction[],
  options?: ExcelExportOptions
) {

  const fileName =
    options?.fileName ||
    "bank-statement-converted.xlsx";


  const sheetName =
    options?.sheetName ||
    "Transactions";



  const rows = transactions.map(
    (transaction) => ({
      Date: transaction.date || "",
      Description:
        transaction.description || "",
      Debit:
        transaction.debit || "",
      Credit:
        transaction.credit || "",
      Balance:
        transaction.balance || "",
    })
  );



  const worksheet =
    XLSX.utils.json_to_sheet(rows);



  /**
   * Column widths
   */
  worksheet["!cols"] = [
    {
      wch: 15,
    },
    {
      wch: 55,
    },
    {
      wch: 15,
    },
    {
      wch: 15,
    },
    {
      wch: 18,
    },
  ];



  /**
   * Freeze first row
   */
  worksheet["!freeze"] = {
    xSplit: 0,
    ySplit: 1,
  };



  /**
   * Auto filter
   */
 if (worksheet["!ref"]) {
  worksheet["!autofilter"] = {
    ref: worksheet["!ref"],
  };
}


  /**
   * Header styling
   */
  const range =
    XLSX.utils.decode_range(
      worksheet["!ref"] || "A1"
    );


  for (
    let col = range.s.c;
    col <= range.e.c;
    col++
  ) {

    const cellAddress =
      XLSX.utils.encode_cell({
        r: 0,
        c: col,
      });


    const cell =
      worksheet[cellAddress];


    if (cell) {

      cell.s = {
        font: {
          bold: true,
          color: "FFFFFF",
        },

        fill: {
          fgColor: {
            rgb: "4F46E5",
          },
        },

        alignment: {
          horizontal: "center",
          vertical: "center",
        },
      };

    }

  }



  /**
   * Number formatting
   */
  for (
    let row = 1;
    row <= range.e.r;
    row++
  ) {


    [
      "C",
      "D",
      "E",
    ].forEach(
      (column) => {

        const cell =
          worksheet[
            `${column}${row + 1}`
          ];


        if (cell) {

          cell.z =
            '#,##0.00';

        }

      }
    );

  }




  const workbook =
    XLSX.utils.book_new();



  XLSX.utils.book_append_sheet(
    workbook,
    worksheet,
    sheetName
  );



  /**
   * Add summary sheet
   */
  const summaryData = [
    {
      Metric: "Total Transactions",
      Value:
        transactions.length,
    },
    {
      Metric: "Generated By",
      Value:
        "Soupxor Bank Statement Converter",
    },
  ];



  const summarySheet =
    XLSX.utils.json_to_sheet(
      summaryData
    );


  summarySheet["!cols"] = [
    {
      wch: 25,
    },
    {
      wch: 35,
    },
  ];



  XLSX.utils.book_append_sheet(
    workbook,
    summarySheet,
    "Summary"
  );



  XLSX.writeFile(
    workbook,
    fileName
  );


  return fileName;
}